import { test, expect } from "@playwright/test";

test("hover and selection have distinct persistent highlights", async ({ page }) => {
  await page.goto("/#explore");
  const scene = page.getByTestId("anatomy-scene");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures")), { timeout: 30_000 }).toBeGreaterThan(300);
  await page.getByRole("checkbox", { name: "Highlight representative sites of action" }).uncheck();
  const canvas = scene.locator("canvas");
  await canvas.scrollIntoViewIfNeeded();
  const bounds = (await canvas.boundingBox())!;
  await page.mouse.move(bounds.x + 10, bounds.y + 150);
  const neutral = await canvas.screenshot();
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .42);
  await expect.poll(async () => Number(await scene.getAttribute("data-hovered-structures"))).toBeGreaterThan(0);
  expect((await canvas.screenshot()).equals(neutral)).toBe(false);
  await canvas.click({ position: { x: bounds.width * .5, y: bounds.height * .42 } });
  await expect.poll(async () => Number(await scene.getAttribute("data-selected-structures"))).toBeGreaterThan(0);
  await page.mouse.move(0, 0);
  await expect(scene).toHaveAttribute("data-hovered-structure", "");
  await expect.poll(async () => Number(await scene.getAttribute("data-selected-structures"))).toBeGreaterThan(0);
  await page.getByRole("combobox", { name: "Search organs" }).fill("lung");
  await page.getByRole("option", { name: /Lungs/ }).click();
  await expect.poll(async () => Number(await scene.getAttribute("data-selected-structures"))).toBeGreaterThan(1);
});

test("wheel zoom follows the pointer instead of the body center", async ({ page }) => {
  await page.goto("/#explore");
  const scene = page.getByTestId("anatomy-scene");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures")), { timeout: 30_000 }).toBeGreaterThan(300);
  const canvas = scene.locator("canvas");
  await canvas.scrollIntoViewIfNeeded();
  let bounds = (await canvas.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width * .16, bounds.y + bounds.height * .5);
  const overview = await canvas.screenshot();
  await page.mouse.wheel(0, -260);
  await expect.poll(async () => (await canvas.screenshot()).equals(overview)).toBe(false);
  const leftZoom = await canvas.screenshot();
  await page.getByRole("button", { name: "Reset body view", exact: true }).click();
  bounds = (await canvas.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width * .84, bounds.y + bounds.height * .5);
  await page.mouse.wheel(0, -260);
  await expect.poll(async () => (await canvas.screenshot()).equals(overview)).toBe(false);
  expect((await canvas.screenshot()).equals(leftZoom)).toBe(false);
});

test("female reference has its own anatomy and persists across medicine guides", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/#explore");
  const scene = page.getByTestId("anatomy-scene");
  await page.getByRole("button", { name: "Female", exact: true }).click();
  await expect(scene).toHaveAttribute("data-body-variant", "female");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures")), { timeout: 30_000 }).toBeGreaterThan(100);
  await expect.poll(async () => Number(await scene.getAttribute("data-highlighted-structures"))).toBeGreaterThan(0);
  await page.locator(".atlas-viewport").screenshot({ path: `test-results/female-${testInfo.project.name}.png` });
  await page.getByRole("combobox", { name: "Isolate a body system" }).selectOption("reproductive");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures"))).toBeGreaterThan(20);
  expect(Number(await scene.getAttribute("data-visible-structures"))).toBeLessThan(70);
  await page.getByRole("button", { name: /^Metformin/ }).click();
  await expect(page.getByRole("button", { name: "Female", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(scene).toHaveAttribute("data-body-variant", "female");
  await expect.poll(async () => Number(await scene.getAttribute("data-highlighted-structures")), { timeout: 30_000 }).toBeGreaterThan(0);
  await page.getByRole("button", { name: "Male", exact: true }).click();
  await expect(scene).toHaveAttribute("data-body-variant", "male");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures")), { timeout: 30_000 }).toBeGreaterThan(300);
  expect(errors).toEqual([]);
});

test("organ search supports aliases, keyboard selection, empty results, and female organs", async ({ page }, testInfo) => {
  await page.goto("/#explore");
  await expect(page.locator(".atlas-organ-list, .atlas-highlight-legend")).toHaveCount(0);
  const search = page.getByRole("combobox", { name: "Search organs" });
  const scene = page.getByTestId("anatomy-scene");
  await search.fill("not-an-organ");
  await expect(page.getByText("No matching organs in this reference.", { exact: false })).toBeVisible();
  await search.fill("renal");
  await search.press("ArrowDown");
  await search.press("Enter");
  await expect(scene).toHaveAttribute("data-focused-structure", "Kidneys", { timeout: 30_000 });
  await expect.poll(async () => Number(await scene.getAttribute("data-selected-structures"))).toBeGreaterThan(0);
  await expect(search).toHaveAttribute("aria-expanded", "false");
  await page.mouse.move(0, 0);
  await page.locator(".atlas-viewport").screenshot({ path: `test-results/selection-outline-${testInfo.project.name}.png` });
  await page.getByRole("button", { name: "Back to full body", exact: true }).click();
  await expect(scene).toHaveAttribute("data-selected-structures", "0");
  await expect(scene).toHaveAttribute("data-focused-structure", "");
  await expect(page.getByRole("combobox", { name: "Isolate a body system" })).toHaveValue("all");
  await expect(search).toHaveValue("");
  await search.fill("cerebrum");
  await search.press("Enter");
  await expect(scene).toHaveAttribute("data-focused-structure", "Brain", { timeout: 30_000 });
  await page.getByRole("button", { name: "Female", exact: true }).click();
  await search.fill("womb");
  await page.getByRole("option", { name: /Uterus/ }).click();
  await expect(scene).toHaveAttribute("data-focused-structure", "Uterus", { timeout: 30_000 });
  await expect.poll(async () => Number(await scene.getAttribute("data-selected-structures"))).toBeGreaterThan(0);
});

test("male and female diagrams share controls, layout, and interaction settings", async ({ page }) => {
  await page.goto("/#explore");
  const scene = page.getByTestId("anatomy-scene");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures")), { timeout: 30_000 }).toBeGreaterThan(300);
  await expect(scene).toHaveAttribute("data-skeletal-structures", "142");
  const controls = page.locator(".atlas-controls");
  const labels = await controls.locator("label").allTextContents();
  const options = await controls.locator("select option").allTextContents();
  const bounds = (await controls.boundingBox())!;
  const viewport = (await page.locator(".atlas-viewport").boundingBox())!;
  await page.getByRole("combobox", { name: "Isolate a body system" }).selectOption("respiratory");
  await page.getByRole("slider", { name: "Organs opacity", exact: true }).fill("55");
  await page.getByRole("checkbox", { name: "Highlight representative sites of action" }).uncheck();
  await page.getByRole("button", { name: "Female", exact: true }).click();
  await expect(scene).toHaveAttribute("data-body-variant", "female");
  await expect.poll(async () => Number(await scene.getAttribute("data-visible-structures")), { timeout: 30_000 }).toBeGreaterThan(20);
  await expect(scene).toHaveAttribute("data-skeletal-structures", "143");
  expect(await controls.locator("label").allTextContents()).toEqual(labels);
  expect(await controls.locator("select option").allTextContents()).toEqual(options);
  const femaleBounds = (await controls.boundingBox())!;
  const femaleViewport = (await page.locator(".atlas-viewport").boundingBox())!;
  expect(femaleBounds.width).toBe(bounds.width);
  expect(femaleBounds.height).toBe(bounds.height);
  expect(femaleViewport.width).toBe(viewport.width);
  expect(femaleViewport.height).toBe(viewport.height);
  await expect(page.getByRole("combobox", { name: "Isolate a body system" })).toHaveValue("respiratory");
  await expect(page.getByRole("slider", { name: "Organs opacity", exact: true })).toHaveValue("55");
  await expect(page.getByRole("checkbox", { name: "Highlight representative sites of action" })).not.toBeChecked();
  const search = page.getByRole("combobox", { name: "Search organs" });
  await search.fill("renal");
  await search.press("Enter");
  await expect(scene).toHaveAttribute("data-focused-structure", "Kidneys", { timeout: 30_000 });
  await expect.poll(async () => Number(await scene.getAttribute("data-selected-structures"))).toBeGreaterThan(0);
  await page.getByRole("button", { name: "Male", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Isolate a body system" })).toHaveValue("urinary");
  await search.fill("renal");
  await search.press("Enter");
  await expect(scene).toHaveAttribute("data-focused-structure", "Kidneys", { timeout: 30_000 });
});
